/**
 * Deterministic illustrative stock: mostly in stock, some low, some sold out —
 * so variant availability UI can be exercised.
 */
function buildVariants(prefix: string, sizes: string[], colours: Colour[], seed: number): Variant[] {
  const out: Variant[] = [];
  colours.forEach((colour, ci) => {
    sizes.forEach((size, si) => {
      const n = (seed * 7 + ci * 13 + si * 5) % 11;
      const stock = n === 0 ? 0 : n < 3 ? n : n + 4;
      out.push({
        id: `${prefix}-${ci}-${si}`,
        sku: `WM-${prefix.toUpperCase()}-${colour.name.slice(0, 3).toUpperCase()}-${size.replace(/\W/g, "")}`,
        size,
        colour: colour.name,
        stock,
      });
    });
  });
  return out;
}

function imgs(name: string, kind: MediaAsset["kind"], tones: MediaAsset["tone"][]): MediaAsset[] {
  const views = ["front view", "detail of the handwork", "styled on model", "back view"];
  return tones.map((tone, i) => ({
    kind,
    tone,
    alt: `${name}, ${views[i % views.length]} (placeholder image)`,
  }));
}

